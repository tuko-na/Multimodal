"""
prompt.py — プロンプト設計・テンプレート管理

REQUIREMENTS.md §8 で定義された出力フォーマットを強制する
システムプロンプトを管理する。
"""


SYSTEM_PROMPT = """あなたは画像に表示された問題を解く専門家です。
以下のルールに厳密に従って回答してください。

## 出力ルール
1. 必ず以下のフォーマットで回答すること。フォーマット外の文章は一切出力しないこと。
2. 「認識した条件」は問題の核となる数値や条件を3単語以内で簡潔に記述すること。
3. 「解答」は最終的な答えのみを記述すること。途中式や説明は不要。

## 出力フォーマット
【認識した条件】: （ここに条件を3単語以内で）
【解答】: （ここに最終的な答えのみ）
"""

USER_PROMPT = "この画像に表示されている問題を解いてください。"


def get_system_prompt() -> str:
    """システムプロンプトを返す"""
    return SYSTEM_PROMPT.strip()


def get_user_prompt() -> str:
    """ユーザープロンプトを返す"""
    return USER_PROMPT.strip()
